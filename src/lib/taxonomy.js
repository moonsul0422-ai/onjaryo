// 정렬 순서를 상수 배열 순서로 고정한다. 목록마다 순서가 달라지지 않게.
const orderBy = (list) => {
  const rank = new Map(list.map((v, i) => [v, i]));
  return (a, b) => (rank.get(a) ?? 999) - (rank.get(b) ?? 999) || a.localeCompare(b, 'ko');
};

